// 输出色域。
//
// 现在的显示器多数是广色域的（Apple 的屏幕、大部分新显示器都是 Display P3），
// 能显示的颜色比 sRGB 多出一圈——最明显的是青绿一带，sRGB 里那点青色一直很憋屈。
// 交换链会尽量输出到显示器支持的最宽色域，具体选中了哪个由 create_swapchain()
// 决定并记在这里，见 swapchain.cpp。
//
// 这件事对写颜色的人意味着什么：你填的 RGB 数值是相对当前输出色域的。在 P3 的
// 屏幕上，(1, 0, 0) 就是 P3 的纯红，比 sRGB 的纯红更鲜——这正是广色域的意义。
//
// 反过来说，如果一个颜色是从别处拿来的、已经绑定了某个色域（最常见的是设计师给
// 的 hex 码，那是 sRGB），直接当成本色域的数值填进来就会偏，需要先做一次色域换算。
// 换算矩阵由两个色域的基色坐标和白点算出来，用到时再加。
#pragma once

namespace vkx {

// 交换链最终输出到哪个色域。
enum class Gamut {
    Srgb,       // 传统 sRGB，所有平台都有
    DisplayP3,  // 广色域，比 sRGB 大一圈
};

// 色域的名字，用来打日志。
const char* gamut_name(Gamut gamut);

}  // namespace vkx
